"""音名换算小工具（整个「MIDI → 小提琴」工具链里最底层的一个零件）。

什么是 MIDI 音高（pitch）？
    MIDI 标准里，每个音符用一个整数表示，叫 pitch。
    数字每增加 1，音高升高一个"半音"（钢琴上相邻两个键的间距）。
    约定：中央 C（钢琴正中间那个 Do）= 60。
    本项目用到的小提琴音域大致在 55（G3，G 弦空弦）到 86 之间。

本文件只做一件事：把 MIDI 数字还原成大家熟悉的音名，比如 69 → "A4"。
别的文件（如 mapping.py）再把这个音名进一步对应到
"应该在哪根弦上、用哪根手指、第几把位"去拉。
"""

# 十二平均律里的 12 个音名，按"半音"顺序排好。
# 用 pitch % 12（除以 12 取余数）就能定位到这 12 个里的某一个。
NOTE_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def midi_to_note_name(pitch: int) -> str:
    """把 MIDI 音高数字换成可读的音名，例如 69 → "A4"、60 → "C4"。

    参数:
        pitch: MIDI 音高编号（0~127）。
    返回:
        形如 "A4" 的字符串：字母是音名，数字是第几个八度（octave）。
    """
    # 算"第几个八度"。MIDI 规定 pitch=0 记作 C-1，
    # 所以每 12 个数是一个八度，整体再减 1。
    # 例：pitch=69 → 69 // 12 - 1 = 4，即第 4 八度。
    octave = pitch // 12 - 1
    # 在 12 个音名里取出对应的那一个。
    # 例：69 % 12 = 9 → NOTE_NAMES[9] = "A"。
    note_name = NOTE_NAMES[pitch % 12]
    # 把音名和八度拼成 "A4" 这种写法。
    return f"{note_name}{octave}"
